// Serialize browser code before Wrangler bundles/minifies the Worker. Function
// toString() inside a deployed Worker can capture renamed identifiers/helpers.
import fs from 'node:fs';
import { travelClientBundle, travelClientCss } from '../shared/model-travel-client.mjs';
const target = new URL('../shared/model-travel-client-source.mjs', import.meta.url);
const output = '// Generated by scripts/build-model-travel-client-source.mjs; edit model-travel-client.mjs / model-travel-eta.mjs.\n'
  + 'const full=' + JSON.stringify(travelClientBundle()) + ';\n'
  + 'const summary=' + JSON.stringify(travelClientBundle(true)) + ';\n'
  + 'export const travelClientCss=' + JSON.stringify(travelClientCss) + ';\n'
  + 'export function travelClientBundle(summaryOnly=false){return summaryOnly?summary:full;}\n';
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target,'utf8') !== output) throw Error('Travel browser source is stale; regenerate and commit it.');
} else fs.writeFileSync(target, output);
