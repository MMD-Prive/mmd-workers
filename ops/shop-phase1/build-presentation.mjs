import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../../', import.meta.url);
const read = (path) => readFile(new URL(path, root),'utf8');
const himai=await read('webflow/himai-shop/shop-v3.html');
const mmd=await read('webflow/mmd-shop/mmd-shop-commerce-footer.html');
const scripts=(s)=>[...s.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/gi)].map(m=>m[1]).join('\n');
const styles=(s)=>[...s.matchAll(/<style\b[^>]*>([\s\S]*?)<\/style>/gi)].map(m=>m[1]).join('\n');
const result='// Generated by ops/shop-phase1/build-presentation.mjs; edit the Webflow sources instead.\n'
  +'export const HIMAI_SCRIPT='+JSON.stringify(scripts(himai))+';\n'
  +'export const MMD_SCRIPT='+JSON.stringify(scripts(mmd))+';\n'
  +'export const HIMAI_STYLE='+JSON.stringify(styles(himai))+';\n';
const target=new URL('himai-chat-worker/src/generated-shop-assets.mjs',root);
if(process.argv.includes('--check')) {
  if(await readFile(target,'utf8')!==result) throw new Error('generated_shop_assets_stale');
} else {
  await writeFile(target,result);
  const html=himai.replace(/<style\b[^>]*>[\s\S]*?<\/style>/gi,'').replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi,'').trim()+'\n';
  await writeFile(new URL('webflow/himai-shop/shop-phase1.html',root),html);
}
console.log('presentation source SHA256 '+createHash('sha256').update(result).digest('hex'));
