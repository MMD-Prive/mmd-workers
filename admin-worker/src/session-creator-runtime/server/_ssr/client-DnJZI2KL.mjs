function withApiDeadline(signal, read) {
	const controller = new AbortController();
	return new Promise((resolve, reject) => {
		let settled = false;
		const finish = (error, value) => {
			if (settled) return;
			settled = true;
			clearTimeout(timer);
			signal?.removeEventListener("abort", cancel);
			if (error) reject(error);
			else resolve(value);
		};
		const cancel = () => {
			controller.abort();
			finish(new ApiError("unavailable", 0, "The read was cancelled."));
		};
		const timer = setTimeout(() => {
			controller.abort();
			const error = new ApiError("unavailable", 0, "The admin backend took too long. Please retry.");
			error.code = "read_timeout";
			finish(error);
		}, API_READ_TIMEOUT_MS);
		if (signal?.aborted) {
			cancel();
			return;
		}
		signal?.addEventListener("abort", cancel, { once: true });
		Promise.resolve().then(() => read(controller.signal)).then((value) => finish(null, value), (error) => finish(error));
	});
}
/** POST a relative admin API path as JSON. Read-only lookups only. */
async function apiPost(path, body, signal) {
	if (!path.startsWith("/")) throw new Error("API paths must be relative");
	return withApiDeadline(signal, async (readSignal) => {
		let res;
		try {
			res = await fetch(path, {
				method: "POST",
				credentials: "include",
				cache: "no-store",
				headers: {
					accept: "application/json",
					"content-type": "application/json"
				},
				body: JSON.stringify(body ?? {}),
				signal: readSignal
			});
		} catch {
			throw new ApiError("unavailable", 0, "The admin backend could not be reached.");
		}
		if (!res.ok) {
			const kind = classify(res.status);
			const err = new ApiError(kind, res.status, failureMessage(kind, res.status));
			try {
				const body = await res.json();
				if (typeof body?.error === "string" && /^[a-z0-9_]{1,64}$/.test(body.error)) err.code = body.error;
			} catch {}
			throw err;
		}
		try {
			return await res.json();
		} catch {
			throw new ApiError("unavailable", res.status, "The admin backend returned an unreadable response.");
		}
	});
}
