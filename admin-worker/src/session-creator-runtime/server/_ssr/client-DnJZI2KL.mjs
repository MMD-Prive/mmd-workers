function classify(status) {
	if (status === 401) return "unauthorized";
	if (status === 403) return "forbidden";
	return "unavailable";
}
function failureMessage(kind, status) {
	switch (kind) {
		case "unauthorized": return "Your operator session is not active or has expired.";
		case "forbidden": return "This operator session is not permitted to view this data.";
		default: return `The admin backend did not answer correctly (HTTP ${status}).`;
	}
}
